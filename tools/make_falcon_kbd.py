#!/usr/bin/env python3
"""Generate CORE/verilog/falcon_kbd_map.v: Atari ST keyboard matrix position -> PS/2 set 2 code.

MegaST's keyboard.vhd produces the ST keyboard matrix (st_matrix_n, bit col*8+row, the layout of
AtariST_MiSTer's ikbd/ps2.sv). The Falcon's IKBD (falcon_ikbd.sv) takes MiSTer PS/2 events and maps
them to ST scan codes (falcon_ikbd_keymap.sv). This script inverts the PS/2 -> matrix table of
ps2.sv and checks the chain matrix -> PS/2 -> ST scan code with the Falcon's table.

    python3 tools/make_falcon_kbd.py            (writes the file, prints the table)
"""
import re, sys, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'CORE')
ps2 = open(os.path.join(root, 'AtariST_MiSTer/rtl/ikbd/ps2.sv')).read()
km  = open(os.path.join(root, 'Falcon_MiSTer/rtl/falcon/falcon_ikbd_keymap.sv')).read()

# ps2.sv: non-extended section, then the extended one
ext_at = ps2.index('/* extended PS keys */')
pat = re.compile(r"if\(kbd_sr\[7:0\] == 8'h([0-9a-fA-F]{2})\) matrix\[\s*(\d+)\]\[(\d)\] <= kbd_release;\s*//\s*(.*)")
inv = {}   # matrix index -> (ext, code, name)
for m in pat.finditer(ps2):
    ext = 1 if m.start() > ext_at else 0
    code, col, row, name = int(m.group(1), 16), int(m.group(2)), int(m.group(3)), m.group(4).strip()
    idx = col * 8 + row
    if idx not in inv or (inv[idx][0] == 1 and ext == 0):   # prefer the non-extended code
        inv[idx] = (ext, code, name)

# falcon_ikbd_keymap.sv: case tables for xe = 0 and xe = 1
kx = km.index('end else begin', km.index('if (!xe) begin'))
fmap = {}
for m in re.finditer(r"8'h([0-9A-Fa-f]{2}): map = 8'h([0-9A-Fa-f]{2});\s*//\s*(.*)", km):
    ext = 1 if m.start() > kx else 0
    fmap[(ext, int(m.group(1), 16))] = (int(m.group(2), 16), m.group(3).strip())

# The two tables give some special keys to different PS/2 keys (ps2.sv: PageUp -> Help, the
# Falcon: PageUp -> keypad '('). For these ST keys, take the PS/2 code that the Falcon maps to
# the right scan code.
ST_CODE = {11 * 8 + 0: 0x62,    # Help
           12 * 8 + 0: 0x61,    # Undo
           13 * 8 + 0: 0x63,    # keypad (
           13 * 8 + 1: 0x64}    # keypad )
by_st = {}
for k, (st, fname) in sorted(fmap.items()):
    by_st.setdefault(st, k)
for idx, st in ST_CODE.items():
    ext, code = by_st[st]
    inv[idx] = (ext, code, inv[idx][2] + f' (Falcon: {fmap[(ext, code)][1]})')

rows = []
for idx in sorted(inv):
    ext, code, name = inv[idx]
    st, fname = fmap.get((ext, code), (None, '-'))
    if idx in ST_CODE and st != ST_CODE[idx]:
        sys.exit(f'matrix {idx}: no PS/2 code for ST scan code {ST_CODE[idx]:02X}')
    rows.append((idx, ext, code, name, st, fname))
    print(f"matrix {idx // 8:2d},{idx % 8} ({idx:3d}): PS/2 {'E0 ' if ext else '   '}{code:02X}  {name:22s} -> ST {st if st is None else f'{st:02X}'}  {fname}")

out = os.path.join(root, 'verilog/falcon_kbd_map.v')
with open(out, 'w') as f:
    f.write("// Generated by tools/make_falcon_kbd.py - do not edit.\n"
            "// Atari ST keyboard matrix position (col*8+row, as keyboard.vhd and AtariST_MiSTer ikbd/ps2.sv)\n"
            "// -> PS/2 set 2 code for the Falcon's IKBD (falcon_ikbd.sv): {valid, E0, code}.\n"
            "// MEGA65 port done by Chris Freeman in 2026, licensed under GPL v3\n\n"
            "module falcon_kbd_map (\n\tinput      [6:0] idx,\n\toutput reg [9:0] ps2\n);\n\n"
            "always @(*) begin\n\tcase (idx)\n")
    for idx, ext, code, name, st, fname in rows:
        f.write(f"\t\t7'd{idx:<3d}: ps2 = {{1'b1, 1'b{ext}, 8'h{code:02X}}};   // {name}\n")
    f.write("\t\tdefault: ps2 = 10'd0;\n\tendcase\nend\n\nendmodule\n")
missing = [r for r in rows if r[4] is None]
print(f"{len(rows)} matrix positions, {len(missing)} without a Falcon scan code: {out}")
sys.exit(1 if missing else 0)
